#!/usr/bin/env python3
"""
Plot timing results from the MPC protocol benchmark.

This script reads the timing_results.csv file generated by benchmark.sh
and creates visualizations showing how execution time scales with matrix size.
"""

import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
import sys
import os


def load_data(filename='timing_results_independent.csv'):
    """Load timing results from CSV file."""
    if not os.path.exists(filename):
        print(f"Error: {filename} not found!")
        print("Please run benchmark.sh first to generate timing data.")
        sys.exit(1)

    try:
        df = pd.read_csv(filename)
        print(f"Loaded {len(df)} data points from {filename}")
        return df
    except Exception as e:
        print(f"Error reading {filename}: {e}")
        sys.exit(1)


def prepare_data(df):
    """Calculate derived columns needed for analysis."""
    df['matrix_size'] = df['n']
    df['total_elements'] = df['n'] * df['m'] * df['k']
    df['time_per_element'] = df['execution_time_seconds'] / df['total_elements']
    df['time_per_nk'] = df['execution_time_seconds'] / (df['n'] * df['k'])
    return df


def plot_execution_time(df, output_file='execution_time_plot.png'):
    """Plot execution time vs matrix size."""

    fig, axes = plt.subplots(2, 3, figsize=(18, 10))
    fig.suptitle('MPC Protocol Execution Time Analysis (q=1)', fontsize=16, fontweight='bold')

    # Plot 1: Time vs n (items)
    ax1 = axes[0, 0]
    ax1.plot(df['n'], df['execution_time_seconds'], 'o-', linewidth=2, markersize=8, color='#2E86AB')
    ax1.set_xlabel('Number of Items (n)', fontsize=11, fontweight='bold')
    ax1.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax1.set_title('Execution Time vs Number of Items', fontsize=12, fontweight='bold')
    ax1.grid(True, alpha=0.3)
    ax1.set_xlim(left=0)
    ax1.set_ylim(bottom=0)

    # Plot 2: Time vs k (features)
    ax2 = axes[0, 1]
    ax2.plot(df['k'], df['execution_time_seconds'], 's-', linewidth=2, markersize=8, color='#A23B72')
    ax2.set_xlabel('Number of Features (k)', fontsize=11, fontweight='bold')
    ax2.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax2.set_title('Execution Time vs Number of Features', fontsize=12, fontweight='bold')
    ax2.grid(True, alpha=0.3)
    ax2.set_xlim(left=0)
    ax2.set_ylim(bottom=0)

    # Plot 3: Time vs m (users) - NEW
    ax3 = axes[0, 2]
    ax3.plot(df['m'], df['execution_time_seconds'], '^-', linewidth=2, markersize=8, color='#F18F01')
    ax3.set_xlabel('Number of Users (m)', fontsize=11, fontweight='bold')
    ax3.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax3.set_title('Execution Time vs Number of Users', fontsize=12, fontweight='bold')
    ax3.grid(True, alpha=0.3)
    ax3.set_xlim(left=0)
    ax3.set_ylim(bottom=0)

    # Plot 4: Time vs total matrix elements (log-log scale)
    ax4 = axes[1, 0]
    ax4.loglog(df['total_elements'], df['execution_time_seconds'], 'D-', linewidth=2, markersize=8, color='#06A77D')
    ax4.set_xlabel('Total Matrix Elements (n × m × k)', fontsize=11, fontweight='bold')
    ax4.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax4.set_title('Log-Log: Time vs Total Elements', fontsize=12, fontweight='bold')
    ax4.grid(True, alpha=0.3, which='both')

    # Plot 5: Time vs n*m (items × users)
    ax5 = axes[1, 1]
    nm_product = df['n'] * df['m']
    ax5.plot(nm_product, df['execution_time_seconds'], 'v-', linewidth=2, markersize=8, color='#D62246')
    ax5.set_xlabel('n × m (Items × Users)', fontsize=11, fontweight='bold')
    ax5.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax5.set_title('Execution Time vs n × m Product', fontsize=12, fontweight='bold')
    ax5.grid(True, alpha=0.3)
    ax5.set_xlim(left=0)
    ax5.set_ylim(bottom=0)

    # Plot 6: Summary table
    ax6 = axes[1, 2]
    ax6.axis('off')

    # Create summary statistics
    summary_text = f"""
    Summary Statistics:

    Total Tests: {len(df)}

    Matrix Size Range:
      • n (items): {df['n'].min()} - {df['n'].max()}
      • m (users): {df['m'].min()} - {df['m'].max()}
      • k (features): {df['k'].min()} - {df['k'].max()}

    Execution Time:
      • Minimum: {df['execution_time_seconds'].min():.2f}s
      • Maximum: {df['execution_time_seconds'].max():.2f}s
      • Mean: {df['execution_time_seconds'].mean():.2f}s
      • Median: {df['execution_time_seconds'].median():.2f}s

    Configuration: q = 1 (single query)
    """

    ax6.text(0.05, 0.5, summary_text, fontsize=10, verticalalignment='center',
             family='monospace', bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.3))

    plt.tight_layout()
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    print(f"Plot saved to: {output_file}")
    plt.show()


def plot_complexity_analysis(df, output_file='complexity_analysis.png'):
    """Analyze and plot the computational complexity."""

    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    fig.suptitle('Computational Complexity Analysis', fontsize=16, fontweight='bold')

    # Plot 1: Time vs m (users) - REPLACES normalized time per element
    ax1 = axes[0, 0]
    ax1.plot(df['m'], df['execution_time_seconds'], 'o-', linewidth=2, markersize=8, color='#06A77D')
    ax1.set_xlabel('Number of Users (m)', fontsize=11, fontweight='bold')
    ax1.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax1.set_title('Execution Time vs Number of Users', fontsize=12, fontweight='bold')
    ax1.grid(True, alpha=0.3)
    ax1.set_xlim(left=0)
    ax1.set_ylim(bottom=0)

    # Plot 2: Complexity fitting for n
    ax2 = axes[0, 1]

    x = df['n'].values
    y = df['execution_time_seconds'].values

    ax2.scatter(x, y, s=100, alpha=0.6, color='#D62246', label='Actual', zorder=3)

    # Fit O(n) linear
    if len(x) > 1:
        z_linear = np.polyfit(x, y, 1)
        p_linear = np.poly1d(z_linear)
        x_smooth = np.linspace(x.min(), x.max(), 100)
        ax2.plot(x_smooth, p_linear(x_smooth), '--', linewidth=2, color='#2E86AB', 
                label=f'O(n) fit: {z_linear[0]:.2e}n + {z_linear[1]:.2f}', alpha=0.7)

        # Fit O(n^2) quadratic
        z_quad = np.polyfit(x, y, 2)
        p_quad = np.poly1d(z_quad)
        ax2.plot(x_smooth, p_quad(x_smooth), '-.', linewidth=2, color='#F18F01',
                label=f'O(n²) fit', alpha=0.7)

    ax2.set_xlabel('Number of Items (n)', fontsize=11, fontweight='bold')
    ax2.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax2.set_title('Complexity Model Fitting (n)', fontsize=12, fontweight='bold')
    ax2.legend(fontsize=9)
    ax2.grid(True, alpha=0.3)
    ax2.set_xlim(left=0)
    ax2.set_ylim(bottom=0)

    # Plot 3: Complexity fitting for m (users)
    ax3 = axes[1, 0]

    x_m = df['m'].values
    y_m = df['execution_time_seconds'].values

    ax3.scatter(x_m, y_m, s=100, alpha=0.6, color='#2E86AB', label='Actual', zorder=3)

    # Fit models for m
    if len(x_m) > 1:
        z_linear_m = np.polyfit(x_m, y_m, 1)
        p_linear_m = np.poly1d(z_linear_m)
        x_m_smooth = np.linspace(x_m.min(), x_m.max(), 100)
        ax3.plot(x_m_smooth, p_linear_m(x_m_smooth), '--', linewidth=2, color='#06A77D',
                label=f'O(m) fit: {z_linear_m[0]:.2e}m + {z_linear_m[1]:.2f}', alpha=0.7)

        # Fit O(m^2) quadratic
        z_quad_m = np.polyfit(x_m, y_m, 2)
        p_quad_m = np.poly1d(z_quad_m)
        ax3.plot(x_m_smooth, p_quad_m(x_m_smooth), '-.', linewidth=2, color='#F18F01',
                label=f'O(m²) fit', alpha=0.7)

    ax3.set_xlabel('Number of Users (m)', fontsize=11, fontweight='bold')
    ax3.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax3.set_title('Complexity Model Fitting (m)', fontsize=12, fontweight='bold')
    ax3.legend(fontsize=9)
    ax3.grid(True, alpha=0.3)
    ax3.set_xlim(left=0)
    ax3.set_ylim(bottom=0)

    # Plot 4: Complexity fitting for k (features)
    ax4 = axes[1, 1]

    x_k = df['k'].values
    y_k = df['execution_time_seconds'].values

    ax4.scatter(x_k, y_k, s=100, alpha=0.6, color='#A23B72', label='Actual', zorder=3)

    # Fit models for k
    if len(x_k) > 1:
        z_linear_k = np.polyfit(x_k, y_k, 1)
        p_linear_k = np.poly1d(z_linear_k)
        x_k_smooth = np.linspace(x_k.min(), x_k.max(), 100)
        ax4.plot(x_k_smooth, p_linear_k(x_k_smooth), '--', linewidth=2, color='#06A77D',
                label=f'O(k) fit: {z_linear_k[0]:.2e}k + {z_linear_k[1]:.2f}', alpha=0.7)

        # Fit O(k^2) quadratic
        z_quad_k = np.polyfit(x_k, y_k, 2)
        p_quad_k = np.poly1d(z_quad_k)
        ax4.plot(x_k_smooth, p_quad_k(x_k_smooth), '-.', linewidth=2, color='#F18F01',
                label=f'O(k²) fit', alpha=0.7)

    ax4.set_xlabel('Number of Features (k)', fontsize=11, fontweight='bold')
    ax4.set_ylabel('Execution Time (seconds)', fontsize=11, fontweight='bold')
    ax4.set_title('Complexity Model Fitting (k)', fontsize=12, fontweight='bold')
    ax4.legend(fontsize=9)
    ax4.grid(True, alpha=0.3)
    ax4.set_xlim(left=0)
    ax4.set_ylim(bottom=0)

    plt.tight_layout()
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    print(f"Complexity analysis saved to: {output_file}")
    plt.show()


def print_summary_table(df):
    """Print a formatted summary table."""
    print("\n" + "="*70)
    print("BENCHMARK RESULTS SUMMARY")
    print("="*70)
    print(f"{'n':>6} {'m':>6} {'k':>6} {'q':>4} {'Time (s)':>12} {'Elements':>12} {'μs/elem':>12}")
    print("-"*70)

    for _, row in df.iterrows():
        time_per_elem = (row['execution_time_seconds'] / row['total_elements']) * 1e6
        print(f"{int(row['n']):>6} {int(row['m']):>6} {int(row['k']):>6} "
              f"{int(row['q']):>4} {row['execution_time_seconds']:>12.3f} "
              f"{int(row['total_elements']):>12} {time_per_elem:>12.3f}")

    print("="*70)


def main():
    """Main function to generate all plots."""
    print("="*70)
    print("MPC Protocol Timing Analysis")
    print("="*70)

    # Load data
    df = load_data()

    # Prepare data BEFORE using it
    df = prepare_data(df)

    # Print summary
    print_summary_table(df)

    # Generate plots
    print("\nGenerating plots...")
    plot_execution_time(df)
    plot_complexity_analysis(df)

    print("\n✓ Analysis complete!")
    print("="*70)


if __name__ == '__main__':
    main()
